export type IconName = keyof typeof ICON_ART;

const iconCache = new Map<string, Grid>();

export function icon(name: IconName, color: string): Grid {
  const key = `${name}:${color}`;
  const hit = iconCache.get(key);
  if (hit) return hit;
  const g = new Grid(16, 16).paste(0, 0, ICON_ART[name], { '#': color });
  iconCache.set(key, g);
  return g;
}
